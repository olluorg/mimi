package mimi.core.behavior

import mimi.core.model.*
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

@Serializable
sealed class GameEvent {
    abstract val tick:   Tick
    abstract val source: EntityId?
    abstract val target: EntityId?

    // ── Input Events ──────────────────────────────────────────────────────────

    @Serializable @SerialName("tap")
    data class Tap(
        val position:      PropertyValue.Vec2,
        override val tick: Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("drag_start")
    data class DragStart(
        val entityId:      EntityId,
        val position:      PropertyValue.Vec2,
        override val tick: Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("drag_move")
    data class DragMove(
        val entityId:      EntityId,
        val position:      PropertyValue.Vec2,
        val delta:         PropertyValue.Vec2,
        override val tick: Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("drop")
    data class Drop(
        val draggedEntity:     EntityId,
        val dropTargetEntity:  EntityId,
        override val tick:     Tick,
        override val source:   EntityId? = null,
        override val target:   EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("hold")
    data class Hold(
        val position:      PropertyValue.Vec2,
        val duration:      Tick,
        override val tick: Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("trace_point")
    data class TracePoint(
        val position:      PropertyValue.Vec2,
        val progress:      Float,
        override val tick: Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("trace_complete")
    data class TraceComplete(
        val pathId:        String,
        val accuracy:      Float,
        override val tick: Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    /**
     * How loud the child is right now, 0..1, while they are making a sound.
     *
     * No recording is kept and no words are recognised. For a child who does
     * not yet speak, *any* voice is the achievement, and judging the words
     * would fail exactly the attempts that matter most. Sent a few times a
     * second while the voice lasts.
     */
    @Serializable @SerialName("voice_level")
    data class VoiceLevel(
        val level:           Float,
        override val tick:   Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    /**
     * The child said something — one utterance, from its first sound to the
     * pause after it.
     *
     * [byAdult] marks an attempt an adult vouched for with the "сказал(а)"
     * button: on a device without a microphone, in a noisy room, or for a
     * whisper the microphone cannot separate from the room, the adult sitting
     * beside the child is the better judge anyway.
     */
    @Serializable @SerialName("vocalization")
    data class Vocalization(
        val durationMs:      Long,
        val peak:            Float,
        val byAdult:         Boolean = false,
        /**
         * The vowel heard — «а», «о», «у», «и», «э» — when the attempt was
         * clearly one of them; null otherwise, and always for the adult's
         * button. Never required: it earns a bonus, not permission.
         */
        val sound:           String? = null,
        override val tick:   Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    // ── System Events (generated by engine after World commit) ────────────────

    /**
     * Time passing, for behaviors that wait.
     *
     * Speech games wait for an answer that may never come, and a pause is the
     * technique itself: the adult models a word, then waits, and waiting is
     * what gives the child room to try. Only sessions with a behavior that asks
     * for it receive these, and they do not count as the child doing anything.
     */
    @Serializable @SerialName("clock_tick")
    data class ClockTick(
        override val tick:   Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("match_success")
    data class MatchSuccess(
        override val source: EntityId,
        override val target: EntityId,
        override val tick:   Tick
    ) : GameEvent()

    @Serializable @SerialName("match_fail")
    data class MatchFail(
        override val source: EntityId,
        override val target: EntityId,
        val reason:          String,
        override val tick:   Tick
    ) : GameEvent()

    @Serializable @SerialName("objective_progressed")
    data class ObjectiveProgressed(
        val objectiveId:     ObjectiveId,
        override val tick:   Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("objective_completed")
    data class ObjectiveCompleted(
        val objectiveId:     ObjectiveId,
        override val tick:   Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("objective_reverted")
    data class ObjectiveReverted(
        val objectiveId:     ObjectiveId,
        override val tick:   Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("objective_locked")
    data class ObjectiveLocked(
        val objectiveId:     ObjectiveId,
        override val tick:   Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("scene_started")
    data class SceneStarted(
        override val tick:   Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    /**
     * The child asked to hear the instruction again.
     *
     * Its own event rather than a second SceneStarted: starting the scene again
     * would also rerun everything else that happens at the start — a state
     * machine's opening, a hint timer — when all that was asked for is the words.
     */
    @Serializable @SerialName("instruction_requested")
    data class InstructionRequested(
        override val tick:   Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("scene_completed")
    data class SceneCompleted(
        override val tick:   Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("scene_reset")
    data class SceneReset(
        override val tick:   Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("scene_state_entered")
    data class SceneStateEntered(
        val stateId:        String,
        override val tick:  Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("scene_state_timeout")
    data class SceneStateTimeout(
        val stateId:        String,
        override val tick:  Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("hint_triggered")
    data class HintTriggered(
        val entityId:        EntityId?,
        val hintLevel:       Int,
        override val tick:   Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("idle_check")
    data class IdleCheck(
        override val tick:   Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()

    @Serializable @SerialName("level_completed")
    data class LevelCompleted(
        val levelIndex:      Int,
        val levelId:         String,
        override val tick:   Tick,
        override val source: EntityId? = null,
        override val target: EntityId? = null
    ) : GameEvent()
}
