import mimi.core.scene.SceneLoader
import org.ollu.mini.scenes.BuiltinScenes
import java.io.File

private const val BASE_URL = "https://olluorg.github.io/mimi"

fun main() {
    val outputDir = File(System.getProperty("catalog.outputDir", "catalog"))
    println("Generating catalog → ${outputDir.absolutePath}")
    generateCatalog(outputDir)
    println("Done.")
}

fun generateCatalog(outputDir: File) {
    outputDir.mkdirs()

    for ((entry, scene) in BuiltinScenes.all) {
        val sceneJson = SceneLoader.serialize(scene)
        val metaBlock = """
  "meta": {
    "title": "${entry.title}",
    "description": "${entry.description}",
    "ageMin": ${entry.ageMin},
    "ageMax": ${entry.ageMax},
    "version": 1,
    "tags": []
  },""".trimIndent()
        // Insert meta right after the opening brace of the scene JSON
        val withMeta = sceneJson.replaceFirst("{", "{\n  $metaBlock")
        File(outputDir, "${scene.sceneId}.json").writeText(withMeta)
        println("  ✓ ${scene.sceneId}.json")
    }

    // catalog.json is auto-generated by publish-catalog.yml in CI.
    // Regenerate locally so the bundle stays in sync.
    File(outputDir, "catalog.json").writeText(buildIndexJson())
    println("  ✓ catalog.json")
}

private fun buildIndexJson(): String {
    val refs = BuiltinScenes.entries.joinToString(",\n") { entry ->
        """    { "id": "${entry.id}", "url": "$BASE_URL/${entry.id}.json" }"""
    }
    return """{
  "version": 2,
  "scenes": [
$refs
  ]
}"""
}
